export const TOTAL_SYSTEM_MODULE_COUNT = NOVEL_SETTING_MODULES.length; // 11
export const TOTAL_SYSTEM_FIELD_COUNT = NOVEL_SETTING_MODULES.reduce(
  (sum, m) => sum + m.fields.length,
  0
); // 220

export const CRITICAL_SETTING_KEYS: Set<string> = new Set(
  NOVEL_SETTING_MODULES.flatMap((mod) =>
    mod.fields.filter((f) => f.isCritical).map((f) => `${mod.id}.${f.id}`)
  )
);

/**
 * Generates a deterministic signature hash of critical system settings so we can detect
 * when the user manually alters critical architectural items after an AI outline sync.
 */
export function computeCriticalSettingsSignature(
  systemSettings?: Record<string, string[]>
): string {
  if (!systemSettings) return '';
  const entries = Array.from(CRITICAL_SETTING_KEYS)
    .sort()
    .map((key) => {
      const vals = (systemSettings[key] || []).map((v) => v.trim()).filter(Boolean).sort();
      return vals.length > 0 ? `${key}:${vals.join('|')}` : '';
    })
    .filter(Boolean);
  return entries.join(';;');
}

/**
 * Counts how many fields across all 11 modules currently have at least 1 selected/custom tag.
 */
export function countConfiguredSystemFields(
  systemSettings?: Record<string, string[]>
): { configuredFields: number; totalTags: number; perModuleCounts: Record<string, number> } {
  const perModuleCounts: Record<string, number> = {};
  let configuredFields = 0;
  let totalTags = 0;

  for (const mod of NOVEL_SETTING_MODULES) {
    let modCount = 0;
    for (const field of mod.fields) {
      const arr = systemSettings?.[`${mod.id}.${field.id}`] || [];
      const clean = arr.filter(Boolean);
      if (clean.length > 0) {
        modCount += 1;
        configuredFields += 1;
        totalTags += clean.length;
      }
    }
    perModuleCounts[mod.id] = modCount;
  }

  return { configuredFields, totalTags, perModuleCounts };
}

/**
 * Compact schema catalog passed to AI during `AI完善大纲` so AI can accurately auto-select
 * matching preset tags (or add concise custom tags) across all 11 modules.
 */
export function buildCompactSchemaGuideForAI(): string {
  return NOVEL_SETTING_MODULES.map((mod) => {
    const fieldLines = mod.fields
      .map(
        (f) =>
          `  - "${mod.id}.${f.id}" (${f.label}): 可选预设 [${f.options.slice(0, 8).join(' / ')}]`
      )
      .join('\n');
    return `### 模块 ${mod.indexLabel} · ${mod.name} (${mod.id})\n${fieldLines}`;
  }).join('\n\n');
}

/**
 * Formats populated 11-module settings into a clean, token-efficient creative contract
 * injected into `buildUnifiedSystemPrompt` for outline, chapter, and reroll stages.
 */
export function formatNovelSystemSettingsForPrompt(
  systemSettings?: Record<string, string[]>,
  systemCustomNotes?: Record<string, string>
): string {
  if (!systemSettings && !systemCustomNotes) return '';

  const moduleBlocks: string[] = [];
  for (const mod of NOVEL_SETTING_MODULES) {
    const itemLines: string[] = [];
    for (const field of mod.fields) {
      const vals = (systemSettings?.[`${mod.id}.${field.id}`] || []).map((v) => v.trim()).filter(Boolean);
      if (vals.length > 0) {
        itemLines.push(`  · ${field.label.replace(/（.*?）/g, '')}：${vals.join('、')}`);
      }
    }
    const extraNote = (systemCustomNotes?.[mod.id] || '').trim();
    if (extraNote) {
      itemLines.push(`  · 模块补充指令：${extraNote}`);
    }
    if (itemLines.length > 0) {
      moduleBlocks.push(`【${mod.indexLabel} ${mod.name}】\n${itemLines.join('\n')}`);
    }
  }

  if (moduleBlocks.length === 0) return '';
  return `\n\n# 商业签约级 11 大系统化小说架构设定（全书强制对齐）\n${moduleBlocks.join('\n\n')}`;
}

/**
 * Exports a complete Commercial Novel Platform Signing Submission Package (.md)
 * ready for 番茄 / 起点 / 晋江 / 七猫内投审稿!
 */
export function exportBookSigningPackageMarkdown(book: Book): string {
  const s = book.settings;
  const totalWords = (book.chapters || []).reduce((acc, ch) => acc + (ch.text?.length || 0), 0);
  const lines: string[] = [];

  lines.push(`# 《${book.title}》商业小说平台签约内投稿件包`);
  lines.push('');
  lines.push(`- **目标投稿平台**：${s.targetPlatform || '全平台通用精品签约'}`);
  lines.push(`- **核心题材分类**：${s.genre || '待定'}`);
  lines.push(`- **文风与叙事规格**：${s.style || '默认'} · ${s.pov || '第三人称'} / ${s.tense || '现在时'} · 单章约 ${s.chapterWords || 3500} 字`);
  lines.push(`- **当前已完稿样章**：共 ${book.chapters.length} 章（累计 ${totalWords.toLocaleString()} 字）`);
  if (s.alternateTitles && s.alternateTitles.length > 0) {
    lines.push(`- **高点击率备选书名**：${s.alternateTitles.map((t) => `《${t.replace(/[《》]/g, '')}》`).join(' / ')}`);
  }
  lines.push('');

  if (s.commercialBlurb) {
    lines.push(`## 一、黄金商业简介（书城投放版）`);
    lines.push('');
    lines.push(s.commercialBlurb.trim());
    lines.push('');
  }

  lines.push(`## 二、故事核心主线大纲`);
  lines.push('');
  lines.push(s.outline || '（尚未填写）');
  lines.push('');

  if (s.characters) {
    lines.push(`## 三、主要角色小传与关系张力`);
    lines.push('');
    lines.push(s.characters.trim());
    lines.push('');
  }

  if (s.world) {
    lines.push(`## 四、世界观与底层力量规则`);
    lines.push('');
    lines.push(s.world.trim());
    lines.push('');
  }

  const sysBlock = formatNovelSystemSettingsForPrompt(s.systemSettings, s.systemCustomNotes);
  if (sysBlock) {
    lines.push(`## 五、11 大精细化架构矩阵设定`);
    lines.push('');
    lines.push(sysBlock.replace('# 商业签约级 11 大系统化小说架构设定（全书强制对齐）', '').trim());
    lines.push('');
  }

  if (s.volumePlan && s.volumePlan.length > 0) {
    lines.push(`## 六、长篇分卷规划蓝图`);
    lines.push('');
    for (const vol of s.volumePlan) {
      lines.push(`### 第 ${vol.volumeIndex} 卷：${vol.title}（${vol.chapterSpan}）`);
      lines.push(`- **核心冲突**：${vol.coreConflict}`);
      lines.push(`- **卷末高潮目标**：${vol.climaxGoal}`);
      lines.push('');
    }
  }

  if (s.chapterOutlines && s.chapterOutlines.length > 0) {
    lines.push(`## 七、分章细纲目录（共 ${s.chapterOutlines.length} 章）`);
    lines.push('');
    for (const co of [...s.chapterOutlines].sort((a, b) => a.chapterIndex - b.chapterIndex)) {
      lines.push(
        `- **第 ${co.chapterIndex} 章《${co.title}》**${co.volumeTag ? ` [${co.volumeTag}]` : ''}：${co.summary}${
          co.hookNote ? ` （章末钩子：${co.hookNote}）` : ''
        }`
      );
    }
    lines.push('');
  }

  if (s.foreshadowLedger && s.foreshadowLedger.length > 0) {
    lines.push(`## 八、草蛇灰线长线伏笔与关键道具台账`);
    lines.push('');
    for (const f of s.foreshadowLedger) {
      const statusLabel = f.status === 'resolved' ? '已回收' : f.status === 'fermenting' ? '发酵中' : '已埋设';
      lines.push(
        `- **【${statusLabel}】${f.name}**（埋设于第 ${f.plantedChapter} 章${
          f.expectedResolveChapter ? ` → 预计回收：${f.expectedResolveChapter}` : ''
        }）：${f.note}`
      );
    }
    lines.push('');
  }

  if (book.chapters && book.chapters.length > 0) {
    const sampleChaps = book.chapters.slice(0, 5);
    lines.push(`## 九、黄金开篇内投样章（前 ${sampleChaps.length} 章正文）`);
    lines.push('');
    for (const ch of sampleChaps) {
      lines.push(`### 第 ${ch.index} 章 ${ch.title}`);
      lines.push('');
      lines.push(ch.text.trim());
      lines.push('');
      lines.push('---');
      lines.push('');
    }
  }

  return lines.join('\n');
}
